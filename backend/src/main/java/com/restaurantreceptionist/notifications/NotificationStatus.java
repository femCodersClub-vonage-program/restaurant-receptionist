package com.restaurantreceptionist.notifications;

public enum NotificationStatus {

	NOT_REQUESTED_CANNOT_RECEIVE,
	NOT_REQUESTED_CAPABILITY_UNKNOWN,
	PENDING,
	REQUEST_FAILED,
	REQUEST_OUTCOME_UNKNOWN,
	ACCEPTED,
	SUBMITTED,
	DELIVERED,
	REJECTED,
	UNDELIVERABLE;

	public boolean isFinal() {
		return switch (this) {
			case NOT_REQUESTED_CANNOT_RECEIVE, NOT_REQUESTED_CAPABILITY_UNKNOWN, REQUEST_FAILED, DELIVERED, REJECTED, UNDELIVERABLE -> true;
			case PENDING, REQUEST_OUTCOME_UNKNOWN, ACCEPTED, SUBMITTED -> false;
		};
	}

	public boolean isProviderStatus() {
		return switch (this) {
			case SUBMITTED, DELIVERED, REJECTED, UNDELIVERABLE -> true;
			case NOT_REQUESTED_CANNOT_RECEIVE, NOT_REQUESTED_CAPABILITY_UNKNOWN, PENDING, REQUEST_FAILED, REQUEST_OUTCOME_UNKNOWN, ACCEPTED -> false;
		};
	}
}
